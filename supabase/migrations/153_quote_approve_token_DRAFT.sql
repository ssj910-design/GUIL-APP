-- 153: 견적 승인 링크 토큰 (2026-10-20, 보안)
-- 견적 ID는 시간 기반(q<ms>)이라 추측이 가능해서, ID만으로는 승인 페이지 조회·승인을 못 하게 견적별 무작위 토큰을 붙인다.
-- 토큰은 견적 발송(알림톡) 때 서버가 만들어 저장하고, 링크(qid:<ID>.<토큰>)에 실려 나간다. 앱 화면에는 내려보내지 않는다.
-- 이미 토큰 없이 나간 링크는 거부된다 — 승인 전 견적은 재발송으로 새 링크를 받아야 한다.
alter table public.quote_requests add column if not exists approve_token text;
